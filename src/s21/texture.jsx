/* Background textures from the s21 kit, ported to the light ground.
 *
 * The originals were built to GLOW: bright marks on near-black. Inverting the
 * palette alone gives you a grey haze, so each one has been re-authored as a
 * faint DARK mark on paper at 0.04–0.10 alpha — texture you notice only when
 * you look for it. The motion logic is untouched.
 *
 * Canvas colours have to be literal strings, so the two constants below mirror
 * tailwind.config.js. They are the only place a hex appears in this file. */
const T = {
  paper:  '#fcfcfb',
  sage:   '#e7efeb',
  ink:    [13, 43, 39],    // #0d2b27
  accent: [15, 107, 98],   // #0f6b62
}

/* ───────────────────────────── DOT PATTERN ───────────────────────────── */

/** Tiled SVG dot grid. A faint ink screen, not an accent glow. */
export function DotPattern({
  width = 24,
  height = 24,
  x = 0,
  y = 0,
  cx = 1,
  cy = 1,
  cr = 1,
  className,
  ...props
}) {
  const id = React.useId()

  return (
    <svg
      aria-hidden="true"
      className={cn('pointer-events-none absolute inset-0 h-full w-full fill-ink/[0.07]', className)}
      {...props}
    >
      <defs>
        <pattern
          id={id}
          width={width}
          height={height}
          patternUnits="userSpaceOnUse"
          patternContentUnits="userSpaceOnUse"
          x={x}
          y={y}
        >
          <circle id="pattern-circle" cx={cx} cy={cy} r={cr} />
        </pattern>
      </defs>
      <rect width="100%" height="100%" strokeWidth={0} fill={`url(#${id})`} />
    </svg>
  )
}

/* ──────────────────────────── HALFTONE DOTS ──────────────────────────── */
// ShaderBackground — generated by the 21st.dev Shader Builder ("Halftone Dots").
// Adapted from Paper Shaders: https://shaders.paper.design/halftone-dots (Apache-2.0).

const VERT = `attribute vec2 a_position;
void main() {
  gl_Position = vec4(a_position, 0.0, 1.0);
}`

const FRAG = `#ifdef GL_FRAGMENT_PRECISION_HIGH
precision highp float;
#else
precision mediump float;
#endif

uniform vec3 u_colors[8];
uniform vec4 u_scene;
uniform vec4 u_shape;
uniform vec4 u_surface;
uniform vec4 u_finish;
uniform vec4 u_transform;
uniform vec4 u_space;
uniform vec4 u_cursor;

#define u_resolution u_scene.xy
#define u_time u_scene.z
#define u_colorCount u_scene.w
#define u_scale u_shape.x
#define u_intensity u_shape.y
#define u_paramA u_shape.z
#define u_warp u_shape.w
#define u_detail u_surface.x
#define u_contrast u_surface.y
#define u_brightness u_surface.z
#define u_saturation u_surface.w
#define u_hue u_finish.x
#define u_vignette u_finish.y
#define u_blur u_finish.z
#define u_grain u_finish.w
#ifdef GL_FRAGMENT_PRECISION_HIGH
#define u_seed u_transform.x
#else
#define u_seed mod(u_transform.x, 31.0)
#endif
#define u_rotate u_transform.y
#define u_drift u_transform.z
#define u_oklab u_transform.w
#define u_offset u_space.xy
#define u_mouse u_space.zw
#define u_cursorPresence u_cursor.x
#define u_cursorEffect u_cursor.y
#define u_cursorStrength u_cursor.z
#define u_cursorRadius u_cursor.w

float hash21(vec2 p) {
#ifndef GL_FRAGMENT_PRECISION_HIGH
  p = mod(p, 31.0);
#endif
  p = fract(p * vec2(234.34, 435.345));
  p += dot(p, p + 34.23);
  return fract(p.x * p.y);
}

float grainHash(vec2 p) {
  vec3 p3 = fract(vec3(p.xyx) * 0.1031);
  p3 += dot(p3, p3.yzx + 33.33);
  return fract((p3.x + p3.y) * p3.z);
}

float noise(vec2 p) {
  vec2 i = floor(p);
  vec2 f = fract(p);
  vec2 u = f * f * (3.0 - 2.0 * f);
  return mix(
    mix(hash21(i), hash21(i + vec2(1.0, 0.0)), u.x),
    mix(hash21(i + vec2(0.0, 1.0)), hash21(i + vec2(1.0, 1.0)), u.x),
    u.y);
}

float fbm(vec2 p) {
  float v = 0.0;
  float a = 0.5;
  for (int i = 0; i < 5; i++) {
    v += a * noise(p);
    p = p * 2.03 + vec2(17.0, 9.2);
    a *= 0.5;
  }
  return v;
}

vec3 srgbToLinear(vec3 c) {
  return mix(c / 12.92, pow((c + 0.055) / 1.055, vec3(2.4)), step(0.04045, c));
}
vec3 linearToSrgb(vec3 c) {
  return mix(c * 12.92, 1.055 * pow(max(c, vec3(0.0)), vec3(1.0 / 2.4)) - 0.055, step(0.0031308, c));
}
vec3 linToOklab(vec3 c) {
  float l = 0.4122214708 * c.r + 0.5363325363 * c.g + 0.0514459929 * c.b;
  float m = 0.2119034982 * c.r + 0.6806995451 * c.g + 0.1073969566 * c.b;
  float s = 0.0883024619 * c.r + 0.2817188376 * c.g + 0.6299787005 * c.b;
  l = pow(max(l, 0.0), 1.0 / 3.0);
  m = pow(max(m, 0.0), 1.0 / 3.0);
  s = pow(max(s, 0.0), 1.0 / 3.0);
  return vec3(
    0.2104542553 * l + 0.7936177850 * m - 0.0040720468 * s,
    1.9779984951 * l - 2.4285922050 * m + 0.4505937099 * s,
    0.0259040371 * l + 0.7827717662 * m - 0.8086757660 * s);
}
vec3 oklabToLin(vec3 c) {
  float l = c.x + 0.3963377774 * c.y + 0.2158037573 * c.z;
  float m = c.x - 0.1055613458 * c.y - 0.0638541728 * c.z;
  float s = c.x - 0.0894841775 * c.y - 1.2914855480 * c.z;
  l = l * l * l; m = m * m * m; s = s * s * s;
  return vec3(
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.7076147010 * s);
}
vec3 mixColour(vec3 a, vec3 b, float t) {
  if (u_oklab > 0.5) {
    vec3 la = linToOklab(srgbToLinear(a));
    vec3 lb = linToOklab(srgbToLinear(b));
    return clamp(linearToSrgb(oklabToLin(mix(la, lb, t))), 0.0, 1.0);
  }
  return mix(a, b, t);
}

vec3 palette(float x) {
  float n = max(u_colorCount - 1.0, 1.0);
  float f = clamp(x, 0.0, 1.0) * n;
  vec3 col = u_colors[0];
  for (int i = 0; i < 7; i++) {
    if (float(i) < n)
      col = mixColour(col, u_colors[i + 1], smoothstep(0.0, 1.0, clamp(f - float(i), 0.0, 1.0)));
  }
  return col;
}

vec3 hueRotate(vec3 col, float a) {
  const mat3 toYIQ = mat3(0.299, 0.596, 0.211, 0.587, -0.274, -0.523, 0.114, -0.322, 0.312);
  const mat3 toRGB = mat3(1.0, 1.0, 1.0, 0.956, -0.272, -1.106, 0.621, -0.647, 1.703);
  vec3 yiq = toYIQ * col;
  float ca = cos(a), sa = sin(a);
  yiq = vec3(yiq.x, yiq.y * ca - yiq.z * sa, yiq.y * sa + yiq.z * ca);
  return toRGB * yiq;
}

vec3 shade(vec2 uv, vec2 p, float t) {
  float cells = 13.0 + u_intensity * 42.0;
  vec2 grid = p * cells;
  vec2 id = floor(grid);
  vec2 local = fract(grid) - 0.5;
  if (mod(id.y, 2.0) > 0.5) local.x += 0.5;
  local.x = fract(local.x + 0.5) - 0.5;
  float source = fbm(p * 2.1 + vec2(t * 0.025, -t * 0.018) + u_seed);
  source = mix(source, 0.5 + 0.5 * sin(p.x * 2.7 + p.y * 1.9), 0.35);
  float radius = (0.08 + source * 0.36) * mix(0.55, 1.45, u_paramA);
  float grain = (hash21(id + u_seed) - 0.5) * u_intensity * 0.08;
  float dotMask = 1.0 - smoothstep(radius - 0.055, radius + 0.025, length(local) + grain);
  return mix(u_colors[0], palette(source), dotMask);
}

void main() {
  vec2 uv = gl_FragCoord.xy / u_resolution.xy;
  vec2 screenUv = uv;
  vec2 p = (gl_FragCoord.xy - 0.5 * u_resolution.xy) / min(u_resolution.x, u_resolution.y);

  float cursorMask = 0.0;
  if (u_cursorPresence > 0.001) {
    vec2 cursor = (0.5 * u_mouse * u_resolution.xy) / min(u_resolution.x, u_resolution.y);
    vec2 cursorDelta = p - cursor;
    if (u_cursorEffect < 0.5) {
      p += cursor * u_cursorPresence * u_cursorStrength * 0.55;
    } else {
      float cursorDistance = length(cursorDelta);
      vec2 cursorDirection = cursorDelta / max(cursorDistance, 0.0001);
      cursorMask = u_cursorPresence * (1.0 - smoothstep(0.0, u_cursorRadius, cursorDistance));
      if (u_cursorEffect < 1.5) {
        p -= cursorDirection * cursorMask * u_cursorStrength * 0.24;
      } else if (u_cursorEffect < 2.5) {
        float cursorAngle = cursorMask * u_cursorStrength * 2.2;
        float cc = cos(cursorAngle), cs = sin(cursorAngle);
        p = cursor + mat2(cc, -cs, cs, cc) * cursorDelta;
      } else if (u_cursorEffect < 3.5) {
        float ripple = sin(cursorDistance / max(u_cursorRadius, 0.001) * 18.0 - u_time * 5.0);
        p -= cursorDirection * ripple * cursorMask * u_cursorStrength * 0.07;
      }
    }
  }

  uv = p * min(u_resolution.x, u_resolution.y) / u_resolution.xy + 0.5;
  p *= u_scale;

  if (abs(u_rotate) > 0.0001) {
    float cr = cos(u_rotate), sr = sin(u_rotate);
    p = mat2(cr, -sr, sr, cr) * p;
  }
  p += u_offset;
  if (u_drift > 0.0001) p += u_drift * vec2(sin(u_time * 0.31), cos(u_time * 0.23));
  if (u_warp > 0.0) {
    p += u_warp * (vec2(fbm(p * u_detail + u_seed), fbm(p * u_detail + vec2(5.2, 1.3))) - 0.5);
  }

  vec3 col;
  if (u_blur > 0.0) {
    float e = u_blur;
    float pe = e * u_scale;
    vec2 uvE = vec2(e) * min(u_resolution.x, u_resolution.y) / u_resolution.xy;
    col  = shade(uv, p, u_time) * 0.36;
    col += shade(uv + vec2(uvE.x, 0.0), p + vec2(pe, 0.0), u_time) * 0.16;
    col += shade(uv - vec2(uvE.x, 0.0), p - vec2(pe, 0.0), u_time) * 0.16;
    col += shade(uv + vec2(0.0, uvE.y), p + vec2(0.0, pe), u_time) * 0.16;
    col += shade(uv - vec2(0.0, uvE.y), p - vec2(0.0, pe), u_time) * 0.16;
  } else {
    col = shade(uv, p, u_time);
  }

  if (abs(u_contrast - 1.0) > 0.0001) col = (col - 0.5) * u_contrast + 0.5;
  if (abs(u_saturation - 1.0) > 0.0001) {
    float luma = dot(col, vec3(0.299, 0.587, 0.114));
    col = mix(vec3(luma), col, u_saturation);
  }
  if (abs(u_hue) > 0.0001) col = hueRotate(col, u_hue);
  if (abs(u_brightness) > 0.0001) col += u_brightness;
  if (u_vignette > 0.0001) {
    float vd = length(screenUv - 0.5) * 1.41421356;
    col *= 1.0 - u_vignette * smoothstep(0.35, 1.0, vd);
  }
  if (u_cursorPresence > 0.001 && u_cursorEffect > 3.5)
    col += (vec3(0.18) + col * 0.12) * cursorMask * u_cursorStrength;
  if (u_grain > 0.0001)
    col += (grainHash(gl_FragCoord.xy + vec2(u_seed * 17.0, u_seed * 31.0)) - 0.5) * u_grain;

  gl_FragColor = vec4(clamp(col, 0.0, 1.0), 1.0);
}
`

/* The only real retokenisation the shader needs: colors[0] is the ground and
 * colors[1..3] are the dot ramp. Paper, then ink at 3.5% and 6.5%, then accent
 * at 10% — the darkest dot in the field is a tenth of a teal, which is as far
 * as a texture can go before it starts competing with body copy.
 * Grain is down from 0.042 to 0.016: on a light ground the same amount of
 * per-pixel noise reads as dirt rather than film. */
const UNIFORMS = {
  colors: [
    [0.9882, 0.9882, 0.9843], // paper  #fcfcfb — the ground
    [0.9554, 0.9595, 0.9552], // ink   @ 3.5%
    [0.9273, 0.9349, 0.9303], // ink   @ 6.5%
    [0.8953, 0.9313, 0.9243], // accent @ 10%
    [0.9882, 0.9882, 0.9843],
    [0.9882, 0.9882, 0.9843],
    [0.9882, 0.9882, 0.9843],
    [0.9882, 0.9882, 0.9843],
  ],
  colorCount: 4,
  scale: 1.26,
  intensity: 0.35,
  paramA: 0.28,
  warp: 0.0,
  detail: 1.824,
  contrast: 1.005,
  brightness: 0.0,
  saturation: 1.0,
  hue: 0.0,
  vignette: 0.0,
  blur: 0.0,
  grain: 0.016,
  seed: 1.0,
  rotate: 0.0,
  offsetX: 0.0,
  offsetY: 0.0,
  drift: 0.0,
  cursorEnabled: true,
  cursorEffect: 2.0,
  cursorStrength: 0.65,
  cursorRadius: 0.46,
  oklab: 0.0,
  timeScale: 0.575,
}

/* React 18 StrictMode mounts effects twice. Dropping the WebGL context on the
 * first teardown would kill the context the second mount needs, so the release
 * is deferred by a tick and cancelled if the canvas comes straight back. */
const pendingContextReleases = new WeakMap()

export function ShaderBackground({ className }) {
  const canvasRef = React.useRef(null)
  const reduced = useReducedMotion()

  React.useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return

    const pendingRelease = pendingContextReleases.get(canvas)
    if (pendingRelease !== undefined) window.clearTimeout(pendingRelease)
    pendingContextReleases.delete(canvas)

    const gl = canvas.getContext('webgl', { antialias: false })
    if (!gl) return

    /* Reduced motion: no clock, no cursor field — one frame and stop. */
    const still = !!reduced
    const cursorEnabled = UNIFORMS.cursorEnabled && !still

    const compile = (type, src) => {
      const s = gl.createShader(type)
      gl.shaderSource(s, src)
      gl.compileShader(s)
      return s
    }

    const program = gl.createProgram()
    const vertexShader = compile(gl.VERTEX_SHADER, VERT)
    const fragmentShader = compile(gl.FRAGMENT_SHADER, FRAG)
    gl.attachShader(program, vertexShader)
    gl.attachShader(program, fragmentShader)
    gl.linkProgram(program)
    gl.deleteShader(vertexShader)
    gl.deleteShader(fragmentShader)
    gl.useProgram(program)

    const buf = gl.createBuffer()
    gl.bindBuffer(gl.ARRAY_BUFFER, buf)
    gl.bufferData(gl.ARRAY_BUFFER, new Float32Array([-1, -1, 3, -1, -1, 3]), gl.STATIC_DRAW)
    const loc = gl.getAttribLocation(program, 'a_position')
    gl.enableVertexAttribArray(loc)
    gl.vertexAttribPointer(loc, 2, gl.FLOAT, false, 0, 0)

    const uni = {
      colors: gl.getUniformLocation(program, 'u_colors'),
      scene: gl.getUniformLocation(program, 'u_scene'),
      shape: gl.getUniformLocation(program, 'u_shape'),
      surface: gl.getUniformLocation(program, 'u_surface'),
      finish: gl.getUniformLocation(program, 'u_finish'),
      transform: gl.getUniformLocation(program, 'u_transform'),
      space: gl.getUniformLocation(program, 'u_space'),
      cursor: gl.getUniformLocation(program, 'u_cursor'),
    }

    gl.uniform3fv(uni.colors, new Float32Array(UNIFORMS.colors.flat()))
    gl.uniform4f(uni.shape, UNIFORMS.scale, UNIFORMS.intensity, UNIFORMS.paramA, UNIFORMS.warp)
    gl.uniform4f(uni.surface, UNIFORMS.detail, UNIFORMS.contrast, UNIFORMS.brightness, UNIFORMS.saturation)
    gl.uniform4f(uni.finish, UNIFORMS.hue, UNIFORMS.vignette, UNIFORMS.blur, UNIFORMS.grain)
    gl.uniform4f(uni.transform, UNIFORMS.seed, UNIFORMS.rotate, UNIFORMS.drift, UNIFORMS.oklab)
    gl.uniform4f(uni.cursor, 0, UNIFORMS.cursorEffect, UNIFORMS.cursorStrength, UNIFORMS.cursorRadius)

    let targetX = 0, targetY = 0, targetPresence = 0
    let mouseX = 0, mouseY = 0, cursorPresence = 0
    let pointerKnown = false, pointerClientX = 0, pointerClientY = 0
    let bounds = canvas.getBoundingClientRect()
    let raf = 0
    let lastNow = null
    let visible = document.visibilityState === 'visible'
    let inView = true
    let disposed = false
    const start = performance.now()
    const timeAnimated = !still && Math.abs(UNIFORMS.timeScale) > 0.0001

    const resizeCanvas = () => {
      const dpr = Math.min(window.devicePixelRatio || 1, 1.5)
      const rawWidth = Math.max(1, Math.round(bounds.width * dpr))
      const rawHeight = Math.max(1, Math.round(bounds.height * dpr))
      const pixelScale = Math.min(1, Math.sqrt(2000000 / Math.max(1, rawWidth * rawHeight)))
      const width = Math.max(1, Math.round(rawWidth * pixelScale))
      const height = Math.max(1, Math.round(rawHeight * pixelScale))
      if (canvas.width !== width || canvas.height !== height) {
        canvas.width = width
        canvas.height = height
        gl.viewport(0, 0, width, height)
      }
    }

    function requestRender() {
      if (!disposed && visible && inView && raf === 0) raf = requestAnimationFrame(render)
    }

    const updatePointerTarget = () => {
      if (!pointerKnown) return
      if (bounds.width === 0 || bounds.height === 0) return
      const inside =
        pointerClientX >= bounds.left && pointerClientX <= bounds.right &&
        pointerClientY >= bounds.top && pointerClientY <= bounds.bottom
      if (!inside) {
        targetPresence = 0
        requestRender()
        return
      }
      const nextX = ((pointerClientX - bounds.left) / bounds.width) * 2 - 1
      const nextY = -(((pointerClientY - bounds.top) / bounds.height) * 2 - 1)
      if (targetPresence === 0 && cursorPresence < 0.01) {
        mouseX = nextX
        mouseY = nextY
      }
      targetX = nextX
      targetY = nextY
      targetPresence = 1
      requestRender()
    }

    const onPointerMove = (event) => {
      pointerKnown = true
      pointerClientX = event.clientX
      pointerClientY = event.clientY
      bounds = canvas.getBoundingClientRect()
      updatePointerTarget()
    }
    const onPointerLeave = () => {
      pointerKnown = false
      targetPresence = 0
      requestRender()
    }
    const updateLayout = () => {
      bounds = canvas.getBoundingClientRect()
      resizeCanvas()
      updatePointerTarget()
      requestRender()
    }

    window.addEventListener('resize', updateLayout)
    if (cursorEnabled) {
      window.addEventListener('pointermove', onPointerMove, { passive: true })
      window.addEventListener('pointercancel', onPointerLeave)
      window.addEventListener('scroll', updateLayout, true)
      window.addEventListener('blur', onPointerLeave)
      document.documentElement.addEventListener('pointerleave', onPointerLeave)
    }

    const resizeObserver = new ResizeObserver(updateLayout)
    resizeObserver.observe(canvas)

    const intersectionObserver = new IntersectionObserver(([entry]) => {
      inView = entry ? entry.isIntersecting : true
      if (inView) requestRender()
      else if (raf !== 0) {
        cancelAnimationFrame(raf)
        raf = 0
        lastNow = null
      }
    })
    intersectionObserver.observe(canvas)

    const onVisibilityChange = () => {
      visible = document.visibilityState === 'visible'
      if (visible) requestRender()
      else if (raf !== 0) {
        cancelAnimationFrame(raf)
        raf = 0
        lastNow = null
      }
    }
    document.addEventListener('visibilitychange', onVisibilityChange)

    function render(now) {
      raf = 0
      if (disposed || !visible || !inView) return
      const dt = lastNow === null ? 0 : Math.min((now - lastNow) / 1000, 0.1)
      lastNow = now
      const follow = 1 - Math.exp(-12 * dt)
      mouseX += (targetX - mouseX) * follow
      mouseY += (targetY - mouseY) * follow
      cursorPresence += (targetPresence - cursorPresence) * follow

      resizeCanvas()
      const clock = still ? 0 : ((now - start) / 1000) * UNIFORMS.timeScale
      gl.uniform4f(uni.scene, canvas.width, canvas.height, clock, UNIFORMS.colorCount)
      gl.uniform4f(uni.space, UNIFORMS.offsetX, UNIFORMS.offsetY, mouseX, mouseY)
      gl.uniform4f(
        uni.cursor,
        cursorEnabled ? cursorPresence : 0,
        UNIFORMS.cursorEffect,
        UNIFORMS.cursorStrength,
        UNIFORMS.cursorRadius,
      )
      gl.drawArrays(gl.TRIANGLES, 0, 3)

      const pointerSettling =
        Math.abs(targetX - mouseX) > 0.001 ||
        Math.abs(targetY - mouseY) > 0.001 ||
        Math.abs(targetPresence - cursorPresence) > 0.001
      if (timeAnimated || pointerSettling) requestRender()
      else lastNow = null
    }

    requestRender()

    return () => {
      disposed = true
      cancelAnimationFrame(raf)
      resizeObserver.disconnect()
      intersectionObserver.disconnect()
      document.removeEventListener('visibilitychange', onVisibilityChange)
      window.removeEventListener('resize', updateLayout)
      if (cursorEnabled) {
        window.removeEventListener('pointermove', onPointerMove)
        window.removeEventListener('pointercancel', onPointerLeave)
        window.removeEventListener('scroll', updateLayout, true)
        window.removeEventListener('blur', onPointerLeave)
        document.documentElement.removeEventListener('pointerleave', onPointerLeave)
      }
      gl.deleteBuffer(buf)
      gl.deleteProgram(program)
      const releaseTimer = window.setTimeout(() => {
        if (pendingContextReleases.get(canvas) !== releaseTimer) return
        pendingContextReleases.delete(canvas)
        const lose = gl.getExtension('WEBGL_lose_context')
        if (lose) lose.loseContext()
        canvas.width = 1
        canvas.height = 1
      }, 0)
      pendingContextReleases.set(canvas, releaseTimer)
    }
  }, [reduced])

  return (
    <canvas ref={canvasRef} className={className} style={{ display: 'block', width: '100%', height: '100%' }} />
  )
}

/* ───────────────────────────── KINETIC GRID ──────────────────────────── */

const CELL_SIZE = 55
const INFLUENCE_RADIUS = 260
const MAX_WARP = 24
const DOT_SPACING = 28
const LERP_SPEED = 0.08
/* Lines are all but invisible at rest — the node dots carry the field. */
const LINE_BASE = { r: T.ink[0], g: T.ink[1], b: T.ink[2], a: 0.05 }
/* Dark marks read heavier than light ones at the same radius, so both node
 * sizes come down from the dark-ground original (1.8 / 3.2). */
const NODE_BASE_RADIUS = 1.4
const NODE_ACTIVE_RADIUS = 2.8

function lerpN(a, b, t) {
  return a + (b - a) * t
}

function lerpColor(base, active, t) {
  const r = Math.round(lerpN(base.r, active.r, t))
  const g = Math.round(lerpN(base.g, active.g, t))
  const b = Math.round(lerpN(base.b, active.b, t))
  const a = lerpN(base.a, active.a, t)
  return `rgba(${r},${g},${b},${a.toFixed(3)})`
}

export default function KineticGrid({ children, className, globalColor = 'default' }) {
  const canvasRef = React.useRef(null)
  const wrapRef = React.useRef(null)
  const mouseRef = React.useRef({ x: -9999, y: -9999 })
  const targetMouseRef = React.useRef({ x: -9999, y: -9999 })
  const ripplesRef = React.useRef([])
  const rafRef = React.useRef(0)
  const sizeRef = React.useRef({ w: 0, h: 0 })
  const reduced = useReducedMotion()

  const getWarpedPoint = React.useCallback(
    (gx, gy, col, row, mouse, ripples, cols, rows) => {
      const edgeMargin = 1.5
      const colPin = Math.min(col / edgeMargin, (cols - 1 - col) / edgeMargin, 1)
      const rowPin = Math.min(row / edgeMargin, (rows - 1 - row) / edgeMargin, 1)
      const pinFactor = colPin * colPin * rowPin * rowPin

      const dx = gx - mouse.x
      const dy = gy - mouse.y
      const dist = Math.sqrt(dx * dx + dy * dy)
      const proximity = Math.max(0, 1 - dist / INFLUENCE_RADIUS) * pinFactor

      let rx = 0, ry = 0
      for (const r of ripples) {
        const rdx = gx - r.x
        const rdy = gy - r.y
        const rdist = Math.sqrt(rdx * rdx + rdy * rdy)
        const waveWidth = 55
        const diff = rdist - r.radius
        if (Math.abs(diff) < waveWidth) {
          const strength = (1 - Math.abs(diff) / waveWidth) * r.opacity * 18 * pinFactor
          const angle = Math.atan2(rdy, rdx)
          const sign = diff < 0 ? -1 : 1
          rx += Math.cos(angle) * strength * sign * -1
          ry += Math.sin(angle) * strength * sign * -1
        }
      }

      if (dist < INFLUENCE_RADIUS && dist > 0 && pinFactor > 0) {
        const t = dist / INFLUENCE_RADIUS
        const eased = t < 0.01 ? 0 : (1 - t) * (1 - t) * Math.min(1, dist / 60)
        const warpAmt = eased * MAX_WARP * pinFactor
        const angle = Math.atan2(dy, dx)
        return {
          pt: {
            x: gx - Math.cos(angle) * warpAmt + rx,
            y: gy - Math.sin(angle) * warpAmt + ry,
          },
          proximity,
        }
      }
      return { pt: { x: gx + rx, y: gy + ry }, proximity }
    },
    [],
  )

  const draw = React.useCallback(
    (now) => {
      const canvas = canvasRef.current
      if (!canvas) return
      const ctx = canvas.getContext('2d')
      if (!ctx) return

      const { w: W, h: H } = sizeRef.current
      const mouse = mouseRef.current
      const ripples = ripplesRef.current

      /* Retokenised: the field is ink on paper. `default` warms toward the
       * teal accent as the pointer nears; `monochrome` stays pure ink on the
       * sage surface. Neither state glows — the response is a darkening. */
      const theme = {
        default: {
          bg: T.paper,
          lineActive: { r: T.accent[0], g: T.accent[1], b: T.accent[2], a: 0.30 },
          nodeActive: { r: T.accent[0], g: T.accent[1], b: T.accent[2], a: 0.55 },
          halo: T.accent.join(','),
          ripple: T.accent.join(','),
        },
        monochrome: {
          bg: T.sage,
          lineActive: { r: T.ink[0], g: T.ink[1], b: T.ink[2], a: 0.28 },
          nodeActive: { r: T.ink[0], g: T.ink[1], b: T.ink[2], a: 0.5 },
          halo: T.ink.join(','),
          ripple: T.ink.join(','),
        },
      }[globalColor || 'default']

      ctx.clearRect(0, 0, W, H)
      ctx.fillStyle = theme.bg
      ctx.fillRect(0, 0, W, H)

      ctx.fillStyle = `rgba(${T.ink.join(',')},0.07)`
      for (let x = DOT_SPACING / 2; x < W; x += DOT_SPACING) {
        for (let y = DOT_SPACING / 2; y < H; y += DOT_SPACING) {
          ctx.beginPath()
          ctx.arc(x, y, 0.7, 0, Math.PI * 2)
          ctx.fill()
        }
      }

      for (let i = ripples.length - 1; i >= 0; i--) {
        const r = ripples[i]
        const age = (now - r.born) / 1000
        r.radius = Math.max(0, age * 400)
        r.opacity = Math.max(0, 1 - age * 1.2)
        if (r.opacity <= 0) ripples.splice(i, 1)
      }

      const cols = Math.max(2, Math.ceil(W / CELL_SIZE)) + 1
      const rows = Math.max(2, Math.ceil(H / CELL_SIZE)) + 1
      const cellW = W / (cols - 1)
      const cellH = H / (rows - 1)

      const pts = []
      const prox = []
      for (let row = 0; row < rows; row++) {
        pts[row] = []
        prox[row] = []
        for (let col = 0; col < cols; col++) {
          const { pt, proximity } = getWarpedPoint(
            col * cellW, row * cellH, col, row, mouse, ripples, cols, rows,
          )
          pts[row][col] = pt
          prox[row][col] = proximity
        }
      }

      const drawSeg = (p1, p2, pr1, pr2) => {
        const avg = (pr1 + pr2) / 2
        const t = avg * avg * (3 - 2 * avg)
        ctx.beginPath()
        ctx.moveTo(p1.x, p1.y)
        ctx.lineTo(p2.x, p2.y)
        ctx.strokeStyle = lerpColor(LINE_BASE, theme.lineActive, t)
        ctx.lineWidth = lerpN(0.8, 1.5, t)
        ctx.stroke()
      }

      ctx.lineCap = 'butt'
      for (let row = 0; row < rows; row++)
        for (let col = 0; col < cols - 1; col++)
          drawSeg(pts[row][col], pts[row][col + 1], prox[row][col], prox[row][col + 1])
      for (let col = 0; col < cols; col++)
        for (let row = 0; row < rows - 1; row++)
          drawSeg(pts[row][col], pts[row + 1][col], prox[row][col], prox[row + 1][col])

      for (let row = 0; row < rows; row++) {
        for (let col = 0; col < cols; col++) {
          const p = pts[row][col]
          const pr = prox[row][col]
          const t = pr * pr * (3 - 2 * pr)
          const r = lerpN(NODE_BASE_RADIUS, NODE_ACTIVE_RADIUS, t)

          if (t > 0.3) {
            /* Was an additive glow. On paper an additive halo is a smudge, so
             * this is now a subtractive wash: the same falloff, drawn dark. */
            const haloR = r + lerpN(0, 6, (t - 0.3) / 0.7)
            const grd = ctx.createRadialGradient(p.x, p.y, r * 0.5, p.x, p.y, haloR)
            grd.addColorStop(0, `rgba(${theme.halo},${(t * 0.09).toFixed(3)})`)
            grd.addColorStop(1, `rgba(${theme.halo},0)`)
            ctx.beginPath()
            ctx.arc(p.x, p.y, haloR, 0, Math.PI * 2)
            ctx.fillStyle = grd
            ctx.fill()
          }

          ctx.beginPath()
          ctx.arc(p.x, p.y, r, 0, Math.PI * 2)
          ctx.fillStyle = lerpColor({ r: T.ink[0], g: T.ink[1], b: T.ink[2], a: 0.09 }, theme.nodeActive, t)
          ctx.fill()
        }
      }

      for (const r of ripples) {
        const safeRadius = Math.max(0, r.radius)
        ctx.beginPath()
        ctx.arc(r.x, r.y, safeRadius, 0, Math.PI * 2)
        ctx.strokeStyle = `rgba(${theme.ripple},${(r.opacity * 0.22).toFixed(3)})`
        ctx.lineWidth = 1.5
        ctx.stroke()
      }
    },
    [getWarpedPoint, globalColor],
  )

  const animate = React.useCallback(
    (now) => {
      const m = mouseRef.current
      const t = targetMouseRef.current
      m.x = lerpN(m.x, t.x, LERP_SPEED)
      m.y = lerpN(m.y, t.y, LERP_SPEED)
      draw(now)
      rafRef.current = requestAnimationFrame(animate)
    },
    [draw],
  )

  React.useEffect(() => {
    const canvas = canvasRef.current
    if (!canvas) return

    /* Sized to its own wrapper, not the viewport — a fixed, full-screen
     * canvas paints over every earlier sibling on the page. */
    const wrap = wrapRef.current
    const still = !!reduced

    const setSize = () => {
      const r = wrap ? wrap.getBoundingClientRect() : null
      const w = Math.max(1, Math.round(r ? r.width : window.innerWidth))
      const h = Math.max(1, Math.round(r ? r.height : window.innerHeight))
      const dpr = Math.min(window.devicePixelRatio || 1, 1.5)
      canvas.width = Math.round(w * dpr)
      canvas.height = Math.round(h * dpr)
      canvas.style.width = w + 'px'
      canvas.style.height = h + 'px'
      const ctx = canvas.getContext('2d')
      if (ctx) ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
      sizeRef.current = { w, h }
      /* Paused fields still have to repaint on resize or they stretch. */
      if (still) draw(performance.now())
    }
    setSize()

    const ro = wrap ? new ResizeObserver(setSize) : null
    if (ro && wrap) ro.observe(wrap)

    if (still) {
      /* One static frame: the grid at rest, no pointer field, no RAF. */
      draw(performance.now())
      return () => { if (ro) ro.disconnect() }
    }

    /* Scoped to the wrapper, not window. The original listened globally, so a
     * click anywhere on the page spawned a ripple in a component the user
     * was nowhere near. */
    const local = (e) => {
      const r = canvas.getBoundingClientRect()
      return { x: e.clientX - r.left, y: e.clientY - r.top }
    }
    const onMouseMove = (e) => { targetMouseRef.current = local(e) }
    const onMouseLeave = () => { targetMouseRef.current = { x: -9999, y: -9999 } }
    const onClick = (e) => {
      const { x, y } = local(e)
      ripplesRef.current.push({ x, y, radius: 0, opacity: 1, born: performance.now() })
    }

    const host = wrap || canvas
    host.addEventListener('mousemove', onMouseMove)
    host.addEventListener('mouseleave', onMouseLeave)
    host.addEventListener('click', onClick)
    rafRef.current = requestAnimationFrame(animate)

    return () => {
      if (ro) ro.disconnect()
      host.removeEventListener('mousemove', onMouseMove)
      host.removeEventListener('mouseleave', onMouseLeave)
      host.removeEventListener('click', onClick)
      if (rafRef.current) cancelAnimationFrame(rafRef.current)
      rafRef.current = 0
    }
  }, [animate, draw, reduced])

  return (
    <div
      ref={wrapRef}
      className={cn(
        'relative w-full min-h-screen overflow-hidden',
        globalColor === 'monochrome' ? 'bg-sage' : 'bg-paper',
        className,
      )}
    >
      <canvas ref={canvasRef} className="absolute inset-0 z-0 h-full w-full pointer-events-none" />
      <div className="relative z-10 w-full h-full">{children}</div>
    </div>
  )
}

export { KineticGrid }
